"""
Tests of symm_rigid_press.

Special Wyckoff positions: XULDUD crystals generated by cgenarris with the
molecule on a site of symmetry 2, m or mm2, at Z = 4 and Z = 8; the site
symmetry must survive the optimization.

Experimental match: a generated aspirin (ACSALA00) crystal must optimize into
the experimental structure.

Image sum: the contact energy of a two-molecule cell whose second molecule sits
outside the cell must equal a brute-force sum over a wide image range.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest
import spglib
from ase import Atoms
from ase.io import read
from pymatgen.analysis.structure_matcher import StructureMatcher
from pymatgen.core import Structure
from pymatgen.io.ase import AseAtomsAdaptor
from scipy.spatial.transform import Rotation

from gnrs.gnrsutil.molecule_bonding import get_vdw_distance_cutoff_matrix
from gnrs.optimize.symm_rigid_press.energy import ContactEnergy, pair_energy
from gnrs.optimize.symm_rigid_press.optimizer import RigidPressSymm

DATA = Path(__file__).parents[1] / "data" / "sp_w"
MOL = DATA / "XULDUD_mol.xyz"
ACSALA00 = Path(__file__).parents[1] / "data" / "ACSALA00"
# (fixture, Z, free centre coordinates, free rotation axes) per site symmetry
CASES = [
    ("z4_site_2", 4, 1, 1),
    ("z4_site_m", 4, 2, 1),
    ("z4_site_mm2", 4, 1, 0),
    ("z8_site_2", 8, 1, 1),
    ("z8_site_m", 8, 2, 1),
    ("z8_site_mm2", 8, 1, 0),
]


def operations(xtal: Atoms) -> list[tuple[np.ndarray, np.ndarray]]:
    """Space group operations of a crystal in its own basis, symprec 1e-3."""
    ds = spglib.get_symmetry_dataset(
        (xtal.cell[:], xtal.get_scaled_positions(), xtal.numbers), symprec=1e-3
    )
    return list(zip(ds.rotations, ds.translations))


def has_operation(ops: list, rot: np.ndarray, trans: np.ndarray) -> bool:
    """Whether (rot, trans) is in ops, translations compared modulo the lattice."""
    return any(
        np.array_equal(r, rot)
        and np.allclose((t - trans + 0.5) % 1 - 0.5, 0, atol=1e-3)
        for r, t in ops
    )


@pytest.mark.parametrize(("name", "z", "n_pos", "n_rot"), CASES)
def test_special_position_keeps_site_symmetry(
    name: str, z: int, n_pos: int, n_rot: int
) -> None:
    mol = read(MOL)
    xtal = read(DATA / f"{name}.in", format="aims")
    cutoff, _ = get_vdw_distance_cutoff_matrix(
        str(MOL), z, sr=0.85, natural_cutoff_mult=1.2
    )
    ops_in = operations(xtal)
    volume_in = xtal.get_volume()

    opt = RigidPressSymm(xtal, [mol], cutoff, tol=0.01, maxiter=5000)
    opt.run(xtal)

    (site,) = opt.coords.sites
    assert (site.directions.shape[1], site.axes.shape[1]) == (n_pos, n_rot)
    assert len(xtal) == z * len(mol)
    assert xtal.get_volume() < volume_in
    ops_out = operations(xtal)
    assert all(has_operation(ops_out, r, t) for r, t in ops_in)
    for i in range(z):
        pos = xtal.positions[i * len(mol) : (i + 1) * len(mol)]
        # Images of improper operations are the inverted reference
        rssd = min(
            Rotation.align_vectors(pos - pos.mean(axis=0), sign * site.ref_pos)[1]
            for sign in (1, -1)
        )
        assert rssd / np.sqrt(len(mol)) < 1e-6


def test_aspirin_optimizes_into_experimental_structure() -> None:
    mol = read(ACSALA00 / "ACSALA00_mol.in", format="aims")
    xtal = read(ACSALA00 / "ACSALA00_gen.in", format="aims")
    exp = Structure.from_file(ACSALA00 / "ACSALA00.cif")
    z = 4
    cutoff, _ = get_vdw_distance_cutoff_matrix(
        str(ACSALA00 / "ACSALA00_mol.in"), z, sr=0.85, natural_cutoff_mult=1.2
    )
    matcher = StructureMatcher(stol=0.5, ltol=0.5, angle_tol=10)
    assert not matcher.fit(exp, AseAtomsAdaptor.get_structure(xtal))

    assert RigidPressSymm(xtal, [mol], cutoff, tol=0.01, maxiter=5000).run(xtal)

    assert matcher.fit(exp, AseAtomsAdaptor.get_structure(xtal))


def test_contact_energy_sums_every_image_of_a_molecule_outside_the_cell() -> None:
    lattice = np.diag([8.0, 30.0, 30.0])
    # Two one-atom molecules of one asymmetric unit, the second one outside the cell
    frac = np.array([[0.15, 0.5, 0.5], [1.4, 0.5, 0.5]])
    mol_atoms = [slice(0, 1), slice(1, 2)]
    radius = np.full((2, 2), 3.0)
    D = 14.0
    contacts = ContactEnergy(mol_atoms, mol_atoms, radius, np.full((2, 2), D), 1.0)
    energy, _, _, min_gap = contacts(lattice, frac)

    pos = frac @ lattice
    shifts = np.arange(-10, 11)[:, None] * lattice[0]
    energy_ref, min_gap_ref = 0.0, np.inf
    for i, j, weight in ((0, 1, 1.0), (0, 0, 0.5), (1, 1, 0.5)):
        keep = shifts if i != j else shifts[np.any(shifts != 0, axis=1)]
        e, *_, gap = pair_energy(
            pos[i : i + 1], pos[j : j + 1], radius[:1, :1], D, weight, keep
        )
        energy_ref += e
        min_gap_ref = min(min_gap_ref, gap)
    assert energy == pytest.approx(energy_ref)
    assert min_gap == pytest.approx(min_gap_ref)
